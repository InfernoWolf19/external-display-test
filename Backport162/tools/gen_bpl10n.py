#!/usr/bin/env python3
# Generates Backport162/BPL10N.h from the iPadOS 16.2 (20C65) SpringBoard.loctable (all languages) for the strings 16.0's SpringBoard.loctable lacks.
# usage: gen_bpl10n.py <16.2 SpringBoard.loctable> <16.0 SpringBoard.loctable> > BPL10N.h
import plistlib, sys
new = plistlib.load(open(sys.argv[1], 'rb'))
old = plistlib.load(open(sys.argv[2], 'rb'))
langs = sorted(k for k in new if k != 'LocProvenance')
keys = sorted(set(new['en']) - set(old['en']))     # keys that only exist in 16.2
def lit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"' or ch == '\\': out.append('\\' + ch)
        elif ch == '\n': out.append('\\n')
        elif o < 0x20: out.append('\\u%04x' % o)
        elif o < 0x80: out.append(ch)
        elif o < 0x10000: out.append('\\u%04x' % o)
        else: out.append('\\U%08x' % o)
    return '@"' + ''.join(out) + '"'
print('// BPL10N.h : GENERATED by tools/gen_bpl10n.py from the iPadOS 16.2 (20C65) SpringBoard.loctable; do not edit.')
print('// The strings that 16.2\'s SpringBoard.loctable has and 16.0\'s lacks (%d keys, %d languages): fallback localisation for the 16.0 SpringBoard (G8, specs/GAPS-IMPLEMENTED-0.7.9.md).' % (len(keys), len(langs)))
print('// Language codes are the loctable\'s own (en, en_GB, pt_PT, zh_CN, zh_TW, zh_HK, es_419, fr_CA, no ...).')
print('#import <Foundation/Foundation.h>')
print('static inline NSDictionary<NSString *, NSDictionary<NSString *, NSString *> *> *BPL10N_Table(void) {')
print('    static NSDictionary *t; static dispatch_once_t once;')
print('    dispatch_once(&once, ^{')
print('        t = @{')
for l in langs:
    d = new[l]
    ents = []
    for k in keys:
        v = d.get(k)
        if isinstance(v, str): ents.append('@"%s": %s' % (k, lit(v)))
    print('            @"%s": @{ %s },' % (l, ', '.join(ents)))
print('        };')
print('    });')
print('    return t;')
print('}')
