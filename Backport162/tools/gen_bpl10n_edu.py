#!/usr/bin/env python3
# Generates Backport162/BPL10NEdu.h from the iPadOS 16.2 (20C65) SpringBoardEducation.app/Localizable.loctable (all languages): the strings of the external display education alert
# (SBEExternalDisplayContentViewController) that the 16.0 SpringBoardEducation.app does not have.  usage: gen_bpl10n_edu.py <16.2 Localizable.loctable> > BPL10NEdu.h
import plistlib, sys
new = plistlib.load(open(sys.argv[1], 'rb'))
langs = sorted(k for k in new if k != 'LocProvenance')
keys = sorted(k for k in new['en'] if k.startswith('EXTERNAL_DISPLAY_'))
def lit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"' or ch == '\\': out.append('\\' + ch)
        elif ch == '\n': out.append('\\n')
        elif o < 0x20: out.append('\\u%04x' % o)
        elif o < 0x80: out.append(ch)
        elif o < 0x10000: out.append('\\u%04x' % o)
        else: out.append('\\U%08x' % o)
    return '@"' + ''.join(out) + '"'
print('// BPL10NEdu.h : GENERATED by tools/gen_bpl10n_edu.py from the iPadOS 16.2 (20C65) SpringBoardEducation.app/Localizable.loctable; do not edit.')
print('// The external display education strings (%d keys, %d languages) for the native education alert (specs/DISPLAY-LEFTOVERS-0.7.9.md item 7).' % (len(keys), len(langs)))
print('#import <Foundation/Foundation.h>')
print('static inline NSDictionary<NSString *, NSDictionary<NSString *, NSString *> *> *BPL10NEdu_Table(void) {')
print('    static NSDictionary *t; static dispatch_once_t once;')
print('    dispatch_once(&once, ^{')
print('        t = @{')
for l in langs:
    d = new[l]
    ents = ['@"%s": %s' % (k, lit(d[k])) for k in keys if isinstance(d.get(k), str)]
    print('            @"%s": @{ %s },' % (l, ', '.join(ents)))
print('        };')
print('    });')
print('    return t;')
print('}')
