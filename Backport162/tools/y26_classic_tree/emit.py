FLAGS=['usesSplashBoard','useSupportedTypesForSplashBoard','bypassesClassicMode','isSydneyLinked','KJH','screenType31']
def emit(name, fn):
    dag,root=make(fn)
    # renumber nodes in DFS order from root so that the array is compact
    order=[]; idx={}
    def visit(n):
        if n in idx: return
        nd=dag.nodes[n]
        if nd[0]=='N':
            visit(nd[2]); visit(nd[3])
        idx[n]=len(order); order.append(n)
    visit(root)
    lines=[]
    for n in order:
        nd=dag.nodes[n]
        if nd[0]=='L':
            lines.append('    { 0, 0, %d, 0, 0, 0, 0 },' % nd[1])
        else:
            key=nd[1]; y=idx[nd[2]]; no=idx[nd[3]]
            if key[0]=='T': lines.append('    { 2, 0, %d, 0, 0, %d, %d },' % (key[1], y, no))
            elif key[0]=='F': lines.append('    { 1, 0, %d, 0, 0, %d, %d },' % (FLAGS.index(key[1]), y, no))
            else:
                op={'EQ':0,'GE':1,'LT':2}[key[0]]; side=0 if key[1]=='L' else 1
                w,h=key[2]
                lines.append('    { 3, %d, %d, %r, %r, %d, %d },' % (op, side, w, h, y, no))
    return 'static const Y26Node %s[] = {\n%s\n};\nstatic const int %s_root = %d;\n' % (name, '\n'.join(lines), name, idx[root]), len(order)
